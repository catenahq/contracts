// check-core-app-names.mjs, run over a scratch repo. Run with
// `node scripts/check-core-app-names.test.mjs`.
import { strict as assert } from "node:assert";
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), "check-core-app-names.mjs");
const work = mkdtempSync(join(tmpdir(), "catena-app-names-test-"));
const DEBT = join(work, ".github", "core-app-names-debt.json");

const git = (...args) =>
  execFileSync("git", ["-c", "user.name=t", "-c", "user.email=t@example.com", ...args], { cwd: work, stdio: "pipe" });
const put = (path, body) => {
  mkdirSync(dirname(join(work, path)), { recursive: true });
  writeFileSync(join(work, path), body);
  git("add", "-A");
};
const run = (...args) => {
  const r = spawnSync(process.execPath, [SCRIPT, ...args], { cwd: work, encoding: "utf-8" });
  return { status: r.status, out: r.stdout + r.stderr };
};
const EXC = join(work, ".github", "core-app-names-exceptions.json");
const exc = () => JSON.parse(readFileSync(EXC, "utf-8"));
const setExc = (files, reasons = { gen: "Generated by a script from the sources." }) =>
  writeFileSync(EXC, JSON.stringify({ reasons, files }));
const debt = () => JSON.parse(readFileSync(DEBT, "utf-8"));

try {
  git("init", "-q");
  mkdirSync(join(work, ".github"));
  put("core/a.yml", "image: nextcloud\nname: Nextcloud\n");
  put("core/b.yml", "image: traefik\nkeycloak postgres catena-admin cloudflared oauth2-proxy gatus healthchecks beszel\n");
  put("outside/c.yml", "nextcloud\n");

  // A repo with no debt file is seeded by --update; paths outside the roots stay out.
  let r = run("core");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("core/a.yml: 2 (debt 0)"), r.out);
  r = run("--update", "core");
  assert.equal(r.status, 0, r.out);
  assert.deepEqual(debt(), { "core/a.yml": 2 });
  r = run("core");
  assert.equal(r.status, 0, r.out);
  assert.ok(r.out.includes("clean"), r.out);

  // Structural names are ignored (core/b.yml is not in the debt and passes).
  // A raised count fails.
  put("core/a.yml", "image: nextcloud\nname: Nextcloud\nurl: NEXTCLOUD\n");
  r = run("core");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("core/a.yml: 3 (debt 2)"), r.out);

  // --update refuses a rise and leaves the file alone.
  r = run("--update", "core");
  assert.equal(r.status, 1, r.out);
  assert.deepEqual(debt(), { "core/a.yml": 2 });

  // A new path fails.
  put("core/a.yml", "image: nextcloud\nname: Nextcloud\n");
  put("core/d.yml", "image: erpnext\n");
  r = run("core");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("core/d.yml: 1 (debt 0)"), r.out);
  put("core/d.yml", "image: traefik\n");

  // A fall without --update fails; --update after the fall passes.
  put("core/a.yml", "image: nextcloud\n");
  r = run("core");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("core/a.yml: 1 (debt 2)"), r.out);
  r = run("--update", "core");
  assert.equal(r.status, 0, r.out);
  assert.deepEqual(debt(), { "core/a.yml": 1 });
  assert.equal(run("core").status, 0);

  // A path drained to zero leaves the debt file.
  put("core/a.yml", "image: traefik\n");
  assert.equal(run("core").status, 1);
  assert.equal(run("--update", "core").status, 0);
  assert.deepEqual(debt(), {});
  assert.equal(run("core").status, 0);

  // Whole words only, any case; letters and digits attach, other characters do not.
  put("core/w.txt", "mynextcloud nextcloudy xnextcloud1 n8nx\nNEXTCLOUD, nextcloud_dir nextcloud-s3 \"N8N\" (WordPress)\n");
  r = run("core");
  assert.ok(r.out.includes("core/w.txt: 5 (debt 0)"), r.out);
  put("core/w.txt", "mynextcloud nextcloudy\n");
  r = run("core");
  assert.equal(r.status, 0, r.out);

  // The spellings an app goes by besides its name count, each as a whole word;
  // portainer is an app.
  put("core/s.txt", "Rocket.Chat talk-hpb catena-nextcloud_talk-hpb JVB occ clamd clamdscan rspamd Synapse Portainer\n");
  r = run("core");
  assert.ok(r.out.includes("core/s.txt: 11 (debt 0)"), r.out);
  put("core/s.txt", "occupied rocketxchat jvbs preoccupied unsynapse portainers mail server\n");
  r = run("core");
  assert.equal(r.status, 0, r.out);

  // Accepted uses: an accepted name passes at any count, an inline sentence counts under other.
  put("acc/g.md", "nextcloud occ Nextcloud nextcloud OCC nextcloud\n");
  put("acc/h.md", "Nextcloud\n");
  setExc({
    "acc/g.md": { names: ["Nextcloud", "occ"], reason: "gen" },
    "acc/h.md": { names: ["nextcloud"], reason: "A sentence of twenty characters." },
  });
  r = run("acc");
  assert.equal(r.status, 0, r.out);
  assert.ok(r.out.includes("clean (2 file(s) scanned; 0 in debt over 0 file(s); 7 accepted over 2 file(s) (gen: 6, other: 1))"), r.out);

  // A counted name the entry does not list fails, naming the path and the reason.
  put("acc/g.md", "nextcloud occ erpnext\n");
  r = run("acc");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes('acc/g.md (accepted: gen): holds "erpnext", not listed'), r.out);
  assert.equal(run("--update", "acc").status, 1);
  assert.equal(exc().files["acc/g.md"].names.length, 2);

  // A listed name the file does not hold fails; --update drops it and adds nothing.
  put("acc/g.md", "nextcloud\n");
  r = run("acc");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes('acc/g.md (accepted: gen): lists "occ"'), r.out);
  assert.equal(run("--update", "acc").status, 0);
  assert.deepEqual(exc().files["acc/g.md"].names, ["Nextcloud"]);
  assert.equal(run("acc").status, 0);

  // A listed path with no counted name, or not tracked, fails; --update drops it.
  put("acc/h.md", "nothing here\n");
  setExc({ ...exc().files, "acc/gone.md": { names: ["nextcloud"], reason: "gen" } });
  r = run("acc");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("acc/h.md (accepted: A sentence"), r.out);
  assert.ok(r.out.includes("acc/gone.md (accepted: gen): holds no counted name or is not tracked"), r.out);
  assert.equal(run("--update", "acc").status, 0);
  assert.deepEqual(Object.keys(exc().files), ["acc/g.md"]);

  // A path both accepted and in the debt file fails.
  writeFileSync(DEBT, JSON.stringify({ "acc/g.md": 1 }));
  r = run("acc");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("acc/g.md (accepted: gen): also in the debt file"), r.out);
  writeFileSync(DEBT, "{}");

  // An unknown name and a short reason fail; "*" accepts any name.
  setExc({ "acc/g.md": { names: ["notanapp"], reason: "short" } });
  r = run("acc");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes('"notanapp" is not in core-app-names.json apps'), r.out);
  assert.ok(r.out.includes("acc/g.md: reason is neither a key"), r.out);
  put("acc/g.md", "nextcloud erpnext zammad\n");
  setExc({ "acc/g.md": { names: ["*"], reason: "gen" } });
  r = run("acc");
  assert.equal(r.status, 0, r.out);
  assert.ok(r.out.includes("3 accepted over 1 file(s) (gen: 3)"), r.out);
  setExc({});

  // A seeded debt file leaves accepted paths out.
  setExc({ "acc/g.md": { names: ["*"], reason: "gen" } });
  rmSync(DEBT);
  put("acc/k.md", "zammad\n");
  assert.equal(run("--update", "acc").status, 0);
  assert.deepEqual(debt(), { "acc/k.md": 1 });
  put("acc/k.md", "traefik\n");
  assert.equal(run("--update", "acc").status, 0);
  setExc({});

  // A name inside a bench pointer is not counted; the same name outside one is.
  put("bp/a.md", "`bench:nextcloud_install` and `bench:erpnext/x#1`\n");
  assert.equal(run("bp").status, 0);
  put("bp/a.md", "`bench:nextcloud_install` nextcloud\n");
  r = run("bp");
  assert.ok(r.out.includes("bp/a.md: 1 (debt 0)"), r.out);
  put("bp/a.md", "bench:nextcloud `audit:nextcloud`\n");
  r = run("bp");
  assert.ok(r.out.includes("bp/a.md: 2 (debt 0)"), r.out);
  rmSync(join(work, "bp"), { recursive: true });
  git("add", "-A");

  // Scanner output and the two bookkeeping files are skipped; a copy elsewhere is counted.
  put("sk/r.sarif", "nextcloud\n");
  put("sk/sub/core-app-names-debt.json", '{"nextcloud": 1}\n');
  r = run("sk");
  assert.ok(r.out.includes("sk/sub/core-app-names-debt.json: 1 (debt 0)") && !r.out.includes("r.sarif"), r.out);
  rmSync(join(work, "sk"), { recursive: true });
  git("add", "-A");
  setExc({ "acc/none.md": { names: ["nextcloud"], reason: "gen" } });
  writeFileSync(DEBT, JSON.stringify({ nextcloud: 1 }));
  r = run(".github");
  assert.ok(r.out.includes("(0 file(s) scanned"), r.out);
  writeFileSync(DEBT, "{}");
  setExc({});

  // Only a bench pointer is stripped, and only the pointer: neighbours stay joined by a space.
  put("gp/a.md", "`audit:check-all`bench:erpnext` x`bench:a`nextcloud `bench:zammad and kimai`\n");
  r = run("gp");
  assert.ok(r.out.includes("gp/a.md: 4 (debt 0)"), r.out);
  rmSync(join(work, "gp"), { recursive: true });
  git("add", "-A");

  // --update refuses an unlisted name even when the reason text reads like a stale entry.
  put("ur/a.md", "nextcloud erpnext\n");
  setExc({ "ur/a.md": { names: ["nextcloud"], reason: "Legal text that no longer holds any code at all." } });
  r = run("--update", "ur");
  assert.equal(r.status, 1, r.out);
  assert.deepEqual(exc().files["ur/a.md"].names, ["nextcloud"]);
  rmSync(join(work, "ur"), { recursive: true });
  git("add", "-A");
  setExc({});

  // A file named like an Object property is counted.
  put("constructor", "nextcloud\n");
  r = run("constructor");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("constructor: 1 (debt 0)"), r.out);
  rmSync(join(work, "constructor"));
  git("add", "-A");

  // "." is the whole repository; --exclude drops a prefix from the scan and from both files.
  for (const d of ["acc", "outside"]) rmSync(join(work, d), { recursive: true });
  put("ex/skip/a.md", "nextcloud\n");
  put("ex/keep/b.md", "erpnext\n");
  r = run(".");
  assert.equal(r.status, 1, r.out);
  assert.ok(r.out.includes("ex/skip/a.md: 1 (debt 0)") && r.out.includes("ex/keep/b.md: 1 (debt 0)"), r.out);
  r = run("--exclude", "ex/skip/", ".");
  assert.ok(!r.out.includes("ex/skip/a.md") && r.out.includes("ex/keep/b.md"), r.out);
  writeFileSync(DEBT, JSON.stringify({ "ex/keep/b.md": 2 }));
  assert.equal(run("--update", "--exclude", "ex/skip", ".").status, 0);
  assert.deepEqual(debt(), { "ex/keep/b.md": 1 });
  writeFileSync(DEBT, JSON.stringify({ "ex/keep/b.md": 1, "ex/skip/old.md": 4 }));
  setExc({ "ex/skip/none.md": { names: ["nextcloud"], reason: "gen" } });
  assert.equal(run("--exclude", "ex/skip", ".").status, 0);
  assert.equal(run("--exclude", "ex/skip").status, 2);
  assert.equal(run("--exclude").status, 2);

  assert.ok(existsSync(DEBT));
  assert.equal(run().status, 2);
} finally {
  rmSync(work, { recursive: true, force: true });
}

console.log("check-core-app-names: ok");
